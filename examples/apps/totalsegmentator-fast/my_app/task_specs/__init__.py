@dataclass(frozen=True)
class PartSpec:
    """One nnUNet model part of a task (one bundle under the task root)."""

    name: str  # model dir name under the task root
    label_offset: int  # added to the part's local labels on merge
    config_name: str = "3d_fullres"  # per-part bundle config dir
    # (3d_fullres_high / 3d_lowres_high for other catalog tasks)
    max_local_label: Optional[int] = None  # None = read from the bundle's dataset.json


@dataclass(frozen=True)
class CropSpec:
    """Crop pre-stage (Phase 18 consumer; Phase 17 = schema + data only).

    Crop composes with any family (single-model or multi-part) — the TS
    catalog proves it (e.g. headneck_muscles = 2-part + 6-label crop).
    """

    source: Optional[str]  # None = TS default crop model; else a TS task NAME
    # (e.g. "craniofacial_structures" — the `teeth` case)
    labels: tuple  # crop label subset, e.g. ("liver",)
    addon: tuple  # per-axis crop padding, e.g. (20, 20, 20)


@dataclass(frozen=True)
class TaskSpec:
    """Pure-data description of one TotalSegmentator task (TS 2.18 default sub-mode)."""

    task_id: object  # TS nnUNet task id or tuple of ids — provenance, not loaded by the app
    family: str  # "single_model" | "multi_part" | "crop_cascade"
    parts: tuple  # tuple[PartSpec, ...]; order IS the later-part-wins merge order (oracle order)
    crop: object  # CropSpec | None (crop composes with any family)
    resample: object  # float | tuple[float, float, float] | None (None = no TS input pre-resample)
    target_spacing: object  # float | tuple — model-spacing target for the preprocess stage
    resample_order: int = 3
    tile_step_size: float = 0.8  # Phase 19 (19-01): generic single-model SlidingWindow
    # step size. TS nnunet.py:568-572 uses 0.8 ONLY for
    # the total family (total/total_v3/total_mr), 0.5 for
    # every other task (e.g. body=299). Default 0.8 keeps
    # the total path byte/behavior-identical.
    trainer: str = ""
    tta: bool = False
    snomed: str = ""  # table attribute name on the descriptions module (total -> "ai_segment_descriptions")
    snomed_module: str = ""  # descriptions module name under my_app/ (total -> "ai_segment_descriptions")
    labels: object = None  # per-task label table: str attr of my_app.ai_segment_descriptions
    # (Phase 17: only "volume_labels"), inline dict[str, int], or None
    output_mode: str = "seg_sr"  # "seg_sr" (DICOM SEG + SR) | "emit_only" (P8 debug path)
    postprocess: tuple = ()  # Phase 19 (19-05): TS-CLI task postprocessing rules,
    # model resolution, PRE-back-resample. Each rule:
    #   ("keep_largest_blob", label_name)  or
    #   ("remove_small_blobs", label_name, size_thr_mm3)
    # Label names resolve against this spec's `labels`
    # table. () = no task postprocessing (total /
    # liver_segments — TS applies none to them).
    # Provenance: TS 2.18 totalsegmentator/nnunet.py:
    # 686-695 (body only). Executed by
    # operators/task_postprocess_operator.py.
    folds: tuple = (0,)  # Phase 21: TS nnUNet fold ids
    # (provenance — the app already loads every
    # fold present in the bundle; (0,1,2,3,4)
    # for aorta_annulus / aortic_dissection /
    # pulmonary_artery_landmarks).
    robust_crop: bool = False  # Phase 21: crop pre-stage uses TS task 297 @
    # 3mm instead of 298 @ 6mm
    # (lung_vessels / liver_lesions /
    # heartchambers_highres; TS python_api.py:397-410).
    remove_outside: tuple = ()  # Phase 21: label names for the TS remove_outside
    # rule (heartchambers_highres:
    # ("heart", "aorta", "inferior_vena_cava")).
    remove_outside_dilation: float = 0.0  # Phase 21: mm dilation for remove_outside
    # (heartchambers_highres: 10.0).
    licensed: bool = False  # Phase 21: requires a commercial TS license;
    # pure registry metadata (14 catalog tasks).


