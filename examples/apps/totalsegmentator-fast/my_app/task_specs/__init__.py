"""Task registry for the totalsegmentator-fast app (Phase 17, plan 17-02, TASK-01).

Tasks are DATA, not code. This module is the single source of truth for all
task-level data: which model parts a task runs, in what order, with what label
offsets, what spacing/resample targets, what crop spec, which label table and
SNOMED description table, and which output mode. Adding a task = adding a
``TASK_REGISTRY`` entry + the model bundles on disk — no DAG code changes.

Sub-mode convention: the registry ships ONE entry per task = the
TotalSegmentator 2.18 ``default`` sub-mode (what this app implements). The
``fast``/``fastest`` sub-modes are expressible spacing variants of the same
topology; they are not shipped in v3.0.

Pure-data import rule: this module imports ONLY the Python standard library.
It must remain importable headless in any Python interpreter (no third-party
or app-runtime imports, no model or corpus files). The one-way
dependency is ``my_app.config`` -> ``my_app.task_specs``; the reverse is
forbidden (it would create a cycle and break headless import).

``labels`` convention (per-task label table, TASK-01):
  * ``str``  -> attribute name of the label table in
    ``my_app.ai_segment_descriptions`` (Phase 17 ships exactly one table:
    ``volume_labels``, 117 entries). Consumers/tests resolve it with
    ``getattr``; ``task_specs`` itself NEVER imports that module.
  * ``dict`` -> inline name -> unified-id label table.
  * ``None`` -> the task emits no label table.
"""

