def get_task_spec(name: str) -> TaskSpec:
    """Return the registry entry for ``name``; fail fast on an unknown task.

    Raises:
        ValueError: naming the unknown value and the sorted valid task set
            (no silent fallback — a bad HOLOSCAN_TASK must die before GPU work).
    """
    try:
        return TASK_REGISTRY[name]
    except KeyError:
        raise ValueError(f"unknown HOLOSCAN_TASK {name!r}; valid tasks: {sorted(TASK_REGISTRY)}") from None


