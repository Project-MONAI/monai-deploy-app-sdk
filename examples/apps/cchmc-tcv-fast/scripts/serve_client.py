"""Committed gRPC client for the persistent MAP serve daemon.

Subcommands (all output compact JSON, no pretty-print):

  health [--host H] [--port P] [--deadline S]
      One CheckHealth call. Prints:
      {"status","models":[{config,trainer,folds,patch_size},...],
       "queue_depth","queue_capacity","in_flight_study_uid"}

  health-watch [--host H] [--port P] [--interval S] [--duration S]
      Poll CheckHealth every --interval seconds for --duration seconds.
      One JSON line per poll: {"t","status","latency_ms","queue_depth",
      "in_flight_study_uid"}. Used to prove fast BUSY answers (<1 s).

  process <study_uid> <input_path> <output_path> [--deadline S]
      One ProcessStudy call. Default deadline 600 s (the documented
      long-RPC deadline). On success prints:
      {"ok": true, "status","latency_ms","stages":[{stage,duration_ms}],
       "stage_at_failure","detail"} and exits 0.
      On gRPC error prints {"ok": false, "code": "<StatusCode.name>",
      "details": "..."} and exits 1 (exit 0 ONLY for a status-OK response).

Flat proto import: inserts the committed ``my_app/proto`` dir onto
sys.path and imports the committed pb2 modules (same convention as the
codegen verification). No regenerated copies live in scripts/.

No container/docker involved — plain stdlib + grpcio.
"""

import argparse
import json
import sys
import time
from pathlib import Path

# --- flat proto import (committed stubs, generated by my_app/proto/codegen.py) ---
PROTO_DIR = Path(__file__).resolve().parents[1] / "my_app" / "proto"
if str(PROTO_DIR) not in sys.path:
    sys.path.insert(0, str(PROTO_DIR))

import grpc  # noqa: E402
import map_service_pb2  # noqa: E402
import map_service_pb2_grpc  # noqa: E402

DEFAULT_PORT = 8765
PROCESS_DEADLINE_S = 600.0  # documented long-RPC deadline


def _models_json(resp: "map_service_pb2.HealthResponse"):
    return [
        {
            "config": m.config,
            "trainer": m.trainer,
            "folds": int(m.folds),
            "patch_size": [int(p) for p in m.patch_size],
        }
        for m in resp.models
    ]


def cmd_health(args) -> int:
    with grpc.insecure_channel(f"{args.host}:{args.port}") as channel:
        stub = map_service_pb2_grpc.MapServiceStub(channel)
        resp = stub.CheckHealth(map_service_pb2.HealthRequest(), timeout=args.deadline)
    print(
        json.dumps(
            {
                "status": resp.status,
                "models": _models_json(resp),
                "queue_depth": int(resp.queue_depth),
                "queue_capacity": int(resp.queue_capacity),
                "in_flight_study_uid": resp.in_flight_study_uid,
            }
        )
    )
    return 0


def cmd_health_watch(args) -> int:
    with grpc.insecure_channel(f"{args.host}:{args.port}") as channel:
        stub = map_service_pb2_grpc.MapServiceStub(channel)
        t0 = time.monotonic()
        while time.monotonic() - t0 < args.duration:
            t_start = time.monotonic()
            try:
                resp = stub.CheckHealth(map_service_pb2.HealthRequest(), timeout=10.0)
                row = {
                    "t": round(time.monotonic() - t0, 3),
                    "status": resp.status,
                    "latency_ms": round((time.monotonic() - t_start) * 1000.0, 2),
                    "queue_depth": int(resp.queue_depth),
                    "in_flight_study_uid": resp.in_flight_study_uid,
                }
            except grpc.RpcError as e:
                row = {
                    "t": round(time.monotonic() - t0, 3),
                    "status": "ERROR",
                    "code": e.code().name if e.code() else "?",
                }
            print(json.dumps(row), flush=True)
            # sleep the remainder of the interval (latency counts against it)
            elapsed_in_cycle = time.monotonic() - t_start
            time.sleep(max(0.0, args.interval - elapsed_in_cycle))
    return 0


def cmd_process(args) -> int:
    req = map_service_pb2.StudyRequest(
        study_uid=args.study_uid,
        input_path=args.input_path,
        output_path=args.output_path,
    )
    try:
        with grpc.insecure_channel(f"{args.host}:{args.port}") as channel:
            stub = map_service_pb2_grpc.MapServiceStub(channel)
            resp = stub.ProcessStudy(req, timeout=args.deadline)
    except grpc.RpcError as e:
        print(
            json.dumps(
                {
                    "ok": False,
                    "code": (e.code().name if e.code() else "?"),
                    "details": e.details() if e.details() else "",
                }
            )
        )
        return 1
    print(
        json.dumps(
            {
                "ok": True,
                "status": resp.status,
                "latency_ms": float(resp.latency_ms),
                "stages": [{"stage": s.stage, "duration_ms": float(s.duration_ms)} for s in resp.stages],
                "stage_at_failure": resp.stage_at_failure,
                "detail": resp.detail,
            }
        )
    )
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="cmd", required=True)

    p_health = sub.add_parser("health", help="one CheckHealth call")
    p_health.add_argument("--host", default="localhost")
    p_health.add_argument("--port", type=int, default=DEFAULT_PORT)
    p_health.add_argument("--deadline", type=float, default=10.0)
    p_health.set_defaults(fn=cmd_health)

    p_watch = sub.add_parser("health-watch", help="poll CheckHealth for --duration seconds")
    p_watch.add_argument("--host", default="localhost")
    p_watch.add_argument("--port", type=int, default=DEFAULT_PORT)
    p_watch.add_argument("--interval", type=float, default=2.0)
    p_watch.add_argument("--duration", type=float, default=60.0)
    p_watch.set_defaults(fn=cmd_health_watch)

    p_proc = sub.add_parser("process", help="one ProcessStudy call (long RPC)")
    p_proc.add_argument("study_uid")
    p_proc.add_argument("input_path")
    p_proc.add_argument("output_path")
    p_proc.add_argument("--host", default="localhost")
    p_proc.add_argument("--port", type=int, default=DEFAULT_PORT)
    p_proc.add_argument("--deadline", type=float, default=PROCESS_DEADLINE_S)
    p_proc.set_defaults(fn=cmd_process)

    args = parser.parse_args()
    return args.fn(args)


if __name__ == "__main__":
    sys.exit(main())
